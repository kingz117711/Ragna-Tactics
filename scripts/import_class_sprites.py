# Motion 40 is the closed fist, 52 the thrust, 80 the swing and 88 the aimed/overhead
# swing (bow, gun, knuckle, two-handed staff). The dictionary below maps a motion to the
# suffix its routes carry, so one body can honour whichever weapon is actually equipped.
MOTION_SLOT = {40: 'fist', 52: 'thrust', 80: 'swing', 88: 'aimed'}


def swing_motions(stem, family):
    """The attack motions to bake for a body, in the order it prefers them."""
    preferred = attack_action(stem, family)
    motions = [preferred]
    for other in ((80, 88, 40) if preferred != 40 else (40,)):
        if other != preferred and (other in (80, 88) or stem in FIST):
            motions.append(other)
    if stem in FIST and 40 not in motions:
        motions.append(40)
    return motions


def body_poses(body_act, body_indexed, body_rgba, head_act, head_indexed, head_rgba,
               attacks, shadow, overlay=None):
    """Idle, walk and one attack action on the 320x280 origin, plus the weapon overlay.

    The overlay is a separate atlas (see `build_weapon`) so the same body can hold a
    different weapon without re-baking the class. Weapon art is painted at the body's
    own anchor, which is exactly where the client places it.
    """
    atlas, actions = Atlas(), {}
    overlay_atlas, overlay_actions = Atlas(), {}
    shadow_image, shadow_layer = shadow
    shadow_id = atlas.add(shadow_image)
    phases = [('idle', 0, 'loop', 'idle'), ('walk', 8, 'all', 'walk')]
    phases += [('attack', attack, 'all', MOTION_SLOT[attack]) for attack in attacks]
    for stance, start, mode, tag in phases:
        for direction in range(8):
            frames = body_act['actions'][start + direction]
            if mode == 'loop':
                frames = [frames[0]] * 3
            delay = int(round(body_act['delays'][start + direction] * 25)) or 100
            route = tag + str(direction)
            z = Z_ORDER['back' if direction in (2, 3, 4, 5) else 'front']
            built, painted = [], []
            for index, frame in enumerate(frames):
                base = ro_sprite.anchor_of(frame)
                layers = [(shadow_id, shadow_layer[4], shadow_layer[5], z['shadow'], 'shadow')]
                body_box = paint(frame, body_indexed, body_rgba)
                if body_box:
                    layers.append((atlas.add(body_box[0]), body_box[1], body_box[2], z['body'], 'body'))
                head_frames = head_act['actions'][start + direction]
                head_frame = head_frames[min(index, len(head_frames) - 1)]
                head_box = paint(head_frame, head_indexed, head_rgba,
                                 (base[0] - ro_sprite.anchor_of(head_frame)[0],
                                  base[1] - ro_sprite.anchor_of(head_frame)[1]))
                if head_box:
                    layers.append((atlas.add(head_box[0]), head_box[1], head_box[2], z['head'], 'head'))
                built.append(layers)
                if overlay and stance == 'attack':
                    held_act, held_indexed, held_rgba = overlay
                    weapon_frames = held_act['actions'][start + direction]
                    weapon_frame = weapon_frames[min(index, len(weapon_frames) - 1)]
                    weapon_box = paint(weapon_frame, held_indexed, held_rgba,
                                       (base[0] - ro_sprite.anchor_of(weapon_frame)[0],
                                        base[1] - ro_sprite.anchor_of(weapon_frame)[1]))
                    painted.append([(overlay_atlas.add(weapon_box[0]), weapon_box[1],
                                     weapon_box[2], z['weapon'], 'weapon')] if weapon_box else [])
            actions[route] = {'delay': delay, 'frames': built}
            if overlay:
                overlay_actions[route] = {'delay': delay, 'frames': painted}
    return finish(atlas, actions), (finish(overlay_atlas, overlay_actions) if overlay else None)


def finish(atlas, actions):
    """Shelf-packed sheet plus the v2 metadata table for one set of actions."""
    sheet, place = atlas.finish()
    table = {}
    for route, action in actions.items():
        table[route] = {'delay': action['delay'], 'frames': [
            [fit([place[i][0], place[i][1], atlas.images[i].width, atlas.images[i].height, x, y, z, slot])
             for i, x, y, z, slot in layers] for layers in action['frames']]}
    layers, poses, action_table = pose_table(table)
    # headBaked tells the runtime the head already sits inside this atlas, so it must not
    # add the shared hair layer on top (the shipped pack keeps hair as its own atlas).
    return {'version': 2, 'width': sheet.width, 'height': sheet.height, 'headBaked': True,
            'layers': layers, 'poses': poses, 'actions': action_table}, sheet


def build_job(job, stem, race, sex, shadow):
    body_act = ro_sprite.read_act((CACHE / f'body/{job}_{sex}.act').read_bytes())
    body_indexed, body_rgba = ro_sprite.read_spr((CACHE / f'body/{job}_{sex}.spr').read_bytes())
    style = HEAD_STYLE if race == HUMAN else '1'
    head_act = ro_sprite.read_act((CACHE / f'head/{race}-{style}_{sex}.act').read_bytes())
    head_indexed, head_rgba = ro_sprite.read_spr((CACHE / f'head/{race}-{style}_{sex}.spr').read_bytes())
    families = weapon_sets(stem, sex)
    default = swing_family(families) or ('mace' if stem in FIST else None)
    (meta, sheet), _ = body_poses(body_act, body_indexed, body_rgba, head_act, head_indexed,
                                  head_rgba, swing_motions(stem, default), shadow)
    idle = [layer for layer in meta['poses'][meta['actions']['idle0']['frames'][0]]
            if meta['layers'][layer][7] in ('body', 'head')]
    height = max(meta['layers'][i][5] + meta['layers'][i][3] for i in idle) - \
        min(meta['layers'][i][5] for i in idle)
    return meta, sheet, height


def swing_family(families):
    """The weapon a class is drawn holding when nothing is equipped: its first-listed one."""
    for family in ('sword', 'twohand', 'spear', 'axe', 'mace', 'dagger', 'knuckle',
                   'katar', 'bow', 'gun', 'rod', 'staff', 'book', 'whip', 'shuriken'):
        if family in families:
            return family
    return None


def build_weapon(body_job, sprite_stem, sex, attack):
    """One weapon overlay: the client's own sprite for this body, on the body's origin.

    `sprite_stem` is the file stem of the weapon set (its folder is a job name such as
    `크루세이더`), while `body_job` is the class body whose attack motion places the hand.
    """
    table = weapon_pins_table()
    record = table[sprite_stem]
    key = f'weapon/{sprite_stem}'
    held = (ro_sprite.read_act((CACHE / f'{key}.act').read_bytes()),
            *ro_sprite.read_spr((CACHE / f'{key}.spr').read_bytes()))
    body_act = ro_sprite.read_act((CACHE / f'body/{body_job}_{sex}.act').read_bytes())
    atlas, actions = Atlas(), {}
    for direction in range(8):
        frames = body_act['actions'][attack + direction]
        delay = int(round(body_act['delays'][attack + direction] * 25)) or 100
        route = MOTION_SLOT[attack] + str(direction)
        z = Z_ORDER['back' if direction in (2, 3, 4, 5) else 'front']
        weapon_frames = held[0]['actions'][attack + direction]
        built = []
        for index, frame in enumerate(frames):
            base = ro_sprite.anchor_of(frame)
            weapon_frame = weapon_frames[min(index, len(weapon_frames) - 1)]
            box = paint(weapon_frame, held[1], held[2],
                        (base[0] - ro_sprite.anchor_of(weapon_frame)[0],
                         base[1] - ro_sprite.anchor_of(weapon_frame)[1]))
            built.append([(atlas.add(box[0]), box[1], box[2], z['weapon'], 'weapon')] if box else [])
        actions[route] = {'delay': delay, 'frames': built}
    meta, sheet = finish(atlas, actions)
    meta['headBaked'] = False
    return meta, sheet


def build(class_ids=None):
    commit = head_commit('devilm/costume-ro')
    pins = prontera_pins()
    records = []
    for job, (race, male, female) in CLASSES.items():
        if class_ids and job not in class_ids:
            continue
        for sex, stem in (('m', male), ('f', female)):
            folder = f'data/sprite/{race}/몸통/{SEX_DIR[sex]}/{stem}_{SEX_DIR[sex]}'
            for ext in ('spr', 'act'):
                records.append(pin_for(pins, commit, 'devilm/costume-ro', f'{folder}.{ext}', f'body/{job}_{sex}.{ext}'))
    for race, style in ((HUMAN, HEAD_STYLE), (DORAM, '1')):
        for sex in ('m', 'f'):
            folder = f'data/sprite/{race}/머리통/{SEX_DIR[sex]}/{style}_{SEX_DIR[sex]}'
            for ext in ('spr', 'act'):
                records.append(pin_for(pins, commit, 'devilm/costume-ro', f'{folder}.{ext}',
                                       f'head/{race}-{style}_{sex}.{ext}'))
    wanted = {s for job, (_, m, f) in CLASSES.items() if not class_ids or job in class_ids
              for s in (m, f)}
    for stem, set_record in sorted(weapon_pins_table().items()):
        if stem.rsplit('_', 2)[0] not in wanted:
            continue
        cache_name = f'weapon/{stem}'
        for ext, record in sorted(set_record['files'].items()):
            records.append({'name': f'{cache_name}.{ext}', 'repo': record['repo'],
                            'path': record['path'], 'blob': record['blob'], 'ref': None,
                            'sha256': record['sha256'], 'bytes': record['bytes']})
    records = [r for r in records if any(r['name'].startswith(p) for p in
               ('body/', 'head/', 'weapon/'))]
    ensure(records)
    shadow = {sex: shadow_for(sex) for sex in ('m', 'f')}
    files, assets = {}, {}
    for job, (race, male, female) in CLASSES.items():
        if class_ids and job not in class_ids:
            continue
        for sex, stem in (('m', male), ('f', female)):
            meta, sheet, figure_height = build_job(job, stem, race, sex, shadow[sex])
            assets[f'base-{job}-{sex}'] = add_record(files, meta, png(sheet))
            assets[f'base-{job}-{sex}']['figureHeight'] = figure_height
            print(f'  base-{job}-{sex}  {assets[f"base-{job}-{sex}"]["width"]}x'
                  f'{assets[f"base-{job}-{sex}"]["height"]}  '
                  f'{assets[f"base-{job}-{sex}"]["imageBytes"] // 1024} KiB')
            for family, sprite_stem in sorted(weapon_sets(stem, sex).items()):
                attack = FAMILY_ATTACK[family]
                wmeta, wsheet = build_weapon(job, sprite_stem, sex, attack)
                assets[f'weapon-{job}-{sex}-{family}'] = add_record(files, wmeta, png(wsheet))
                print(f'    weapon-{job}-{sex}-{family}  {wmeta["width"]}x{wmeta["height"]}')
    return files, assets, records, commit


def merge_index(assets):
    """Fold the pack into the runtime index, keeping it a pure derived subset."""
    index = read_json(INDEX)
    previous = index.get('classWardrobe') or {}
    class_assets = dict(previous)
    class_assets.update(assets)
    kept = {}
    for key, entry in sorted(class_assets.items()):
        job = int(key.split('-')[1])
        if job in CLASSES and (OUT / entry['meta']).exists() and (OUT / entry['image']).exists():
            kept[key] = entry
    index['classWardrobe'] = kept
    INDEX.write_text(json.dumps(index, separators=(',', ':')), encoding='utf-8')
    return kept


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--verify', action='store_true')
    parser.add_argument('--sheet')
    parser.add_argument('--only', nargs='*', type=int)
    args = parser.parse_args()
    if args.verify:
        return verify()
    if args.sheet:
        return contact_sheet(args.sheet, args.only or [])
    files, assets, records, commit = build(set(args.only) if args.only else None)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (OUT / name).write_bytes(data)
    for stale in OUT.iterdir():
        if stale.name not in files:
            stale.unlink()
    kept = merge_index(assets)
    manifest = read_json(MANIFEST) if MANIFEST.exists() else {'files': [], 'outputs': {}}
    manifest.update({
        'note': 'Native Ragnarok Online client files, decoded and composited as the client does. '
                'Reuse does not grant ownership of the underlying artwork.',
        'repository': 'devilm/costume-ro', 'commit': commit,
        'headStyle': HEAD_STYLE,
        'files': {r['name']: {'repo': r['repo'], 'path': r['path'], 'blob': r['blob'],
                              'sha256': digest((CACHE / r['name']).read_bytes()),
                              'bytes': (CACHE / r['name']).stat().st_size} for r in records},
        'outputs': {name: digest(data) for name, data in sorted(files.items())},
        'index': {key: {'meta': entry['meta'], 'image': entry['image']} for key, entry in sorted(kept.items())},
    })
    MANIFEST.write_text(json.dumps(manifest, indent=1) + '\n', encoding='utf-8')
    total = sum(len(data) for data in files.values())
    print(f'wrote {len(files)} files ({total / 1048576:.2f} MiB) for {len(kept)} class outfits')
    return 0


def frame_bounds(entry, folder):
    """Lowest and highest pixel row across every exported route, relative to the ground point."""
    meta = read_json(folder / entry['meta'])
    if 'layers' in meta:
        meta['poses'] = [[meta['layers'][i] for i in pose] for pose in meta['poses']]
    top = bottom = None
    for poses in meta['poses']:
        for layer in poses:
            low, high = layer[5] - ORIGIN[1], layer[5] + layer[3] - ORIGIN[1]
            top = low if top is None else min(top, low)
            bottom = high if bottom is None else max(bottom, high)
    return top, bottom


def verify():
    manifest = read_json(MANIFEST)
    for name, expected in manifest['outputs'].items():
        path = OUT / name
        assert path.exists(), path
        assert digest(path.read_bytes()) == expected, path
    # A sprite that floats or sinks is the usual failure of a body swap: every class must
    # stand on the ground point the shipped outfits use (feet at the ground, head above).
    for key, entry in read_json(INDEX)['classWardrobe'].items():
        if key.startswith('weapon-'):
            continue
        top, bottom = frame_bounds(entry, OUT)
        assert -120 <= top <= -50, (key, 'too tall or too short', top)
        # Idle art sits on the ground point; a few attack frames reach a couple of pixels
        # further because the client's sword arm drops below the feet line mid-swing.
        assert 0 <= bottom <= 34, (key, 'feet off the ground point', bottom)
        # A body must swing with the character's own attack motion, not just idle.
        meta = read_json(OUT / entry['meta'])
        assert any(route.rstrip('01234567') in ('swing', 'aimed', 'fist', 'thrust')
                   for route in meta['actions']), (key, 'no attack motion')
    index = read_json(INDEX)
    assert sorted(index['classWardrobe']) == sorted(manifest['index'])
    for key, entry in index['classWardrobe'].items():
        assert entry['meta'] in manifest['outputs'] and entry['image'] in manifest['outputs'], key
        assert (OUT / entry['meta']).exists() and (OUT / entry['image']).exists(), key
    for job, (race, male, female) in CLASSES.items():
        for sex, stem in (('m', male), ('f', female)):
            assert f'base-{job}-{sex}' in index['classWardrobe'], (job, sex)
            for family in weapon_sets(stem, sex):
                assert f'weapon-{job}-{sex}-{family}' in index['classWardrobe'], (job, sex, family)
    print(f'Verified {len(manifest["outputs"])} class sprite files and {len(index["classWardrobe"])} outfits.')


def contact_sheet(path, jobs):
    index = read_json(INDEX)
    classes = [job for job in CLASSES if f'base-{job}-m' in index['classWardrobe']]
    classes = jobs or classes
    cw, ch = 120, 150
    columns = 6
    rows = (len(classes) + columns - 1) // columns
    sheet = Image.new('RGBA', (cw * columns, ch * rows), (52, 60, 72, 255))
    for position, job in enumerate(classes):
        entry = index['classWardrobe'][f'base-{job}-m']
        meta = read_json(OUT / entry['meta'])
        if 'layers' in meta:
            meta['poses'] = [[meta['layers'][i] for i in pose] for pose in meta['poses']]
        atlas = Image.open(OUT / entry['image']).convert('RGBA')
        canvas = Image.new('RGBA', CANVAS)
        for layer in sorted(meta['poses'][meta['actions']['idle0']['frames'][0]], key=lambda l: l[6]):
            canvas.alpha_composite(atlas.crop((layer[0], layer[1], layer[0] + layer[2], layer[1] + layer[3])),
                                   (layer[4], layer[5]))
        crop = canvas.crop((ORIGIN[0] - cw // 2, ORIGIN[1] - ch + 12, ORIGIN[0] + cw // 2, ORIGIN[1] + 12))
        sheet.alpha_composite(crop, ((position % columns) * cw, (position // columns) * ch))
    sheet.save(path)
    print('wrote', path)
    return 0


