def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def dump(value):
    return json.dumps(value, separators=(',', ':')).encode('utf-8')


def digest(data):
    return hashlib.sha256(data).hexdigest()


# ------------------------------------------------------------------ GitHub access
def api(url, raw=False):
    headers = {'User-Agent': 'Ragna-Tactics-class-import'}
    if raw:
        headers['Accept'] = 'application/vnd.github.raw'
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=180) as response:
        data = response.read()
    return data if raw else json.loads(data)


def raw_file(repo, ref, path):
    return api(f'{GITHUB}/repos/{repo}/contents/{quote(path)}?ref={quote(ref)}', raw=True)


def blob_file(repo, sha):
    payload = api(f'{GITHUB}/repos/{repo}/git/blobs/{sha}')
    import base64
    return base64.b64decode(payload['content'])


def head_commit(repo):
    return api(f'{GITHUB}/repos/{repo}/commits/main')['sha']


# ------------------------------------------------------------------ source index
def prontera_pins():
    """The owner repository's own pin of the same client files, keyed by repository path.

    Reusing these pins keeps both projects reading byte-identical sources and avoids a
    second, hand-maintained map for the weapon sprites.
    """
    commit = head_commit('KzeR7/Prontera-Grind')
    pins = {}
    for path in ('tools/native-wardrobe/source-manifest.json',
                 'tools/native-expanded/source-manifest.json'):
        # The expanded manifest annotates some paths ("... (stored under its CP949 name)");
        # strip that so a lookup by real repository path still matches.
        for record in json.loads(raw_file('KzeR7/Prontera-Grind', commit, path))['files']:
            clean = record['path'].split(' (stored under')[0]
            pins.setdefault(clean, record)
    return pins


def korean_local(name):
    """A repository file name in its CP949 form, whichever way the manifest spells it."""
    if any('\uac00' <= c <= '\ud7a3' for c in name):
        return name
    try:
        return name.encode('latin-1').decode('cp949')
    except UnicodeError:
        return name


def split_weapon_stem(stem, jobs):
    """`<job>_<남|여>[_<tail>]` -> (job, sex, tail), matching the longest known job name."""
    for job in sorted(jobs, key=len, reverse=True):
        head = job + '_'
        if not stem.startswith(head):
            continue
        rest = stem[len(head):]
        sex, _, tail = rest.partition('_')
        if sex in ('남', '여'):
            return job, sex, tail
    return None


def pinned_weapons(pins, jobs):
    """Every collected weapon set, keyed by the client file stem `<job>_<sex>_<tail>`."""
    out = {}
    for path, record in pins.items():
        if not path.startswith(WEAPON_SET_REPO_PATH + '/'):
            continue
        local = korean_local(path.rsplit('/', 1)[-1])
        if not local.endswith(('.spr', '.act')):
            continue
        stem, ext = local.rsplit('.', 1)
        if split_weapon_stem(stem, jobs) is None:
            continue
        out.setdefault(stem, {})[ext] = {
            'repo': record['repo'], 'path': path, 'blob': record['blob'],
            'sha256': record['sha256'], 'bytes': record['bytes']}

    # Client-collected sets carry their local name in the key already.
    for name, record in WEAPON_SETS.items():
        stem, ext = name[len('weapon/'):].rsplit('.', 1)
        out.setdefault(stem, {})[ext] = {
            'repo': WEAPON_SET_REPO, 'path': record['path'], 'blob': record['blob'],
            'sha256': None, 'bytes': record['bytes']}
    return {k: v for k, v in out.items() if {'spr', 'act'} <= set(v)}


def weapon_stems():
    """Every job name the wardrobe draws, i.e. the first half of a weapon file name."""
    return {stem for _, (_, male, female) in CLASSES.items() for stem in (male, female)}


def weapon_stem(job, sex):
    """The client file stem of the weapon set a class line of the wardrobe holds."""
    return f'{job}_{sex}'


def pin_for(pins, commit, repo, path, name):
    """One download record: by pinned blob id when the owner repository already pins it."""
    record = pins.get(path)
    if record and record.get('repo') == repo:
        return {'name': name, 'repo': repo, 'path': path, 'blob': record['blob'],
                'ref': None, 'sha256': record['sha256'], 'bytes': record['bytes']}
    return {'name': name, 'repo': repo, 'path': path, 'blob': None,
            'ref': commit, 'sha256': None, 'bytes': None}


