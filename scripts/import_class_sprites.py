def weapon_sets(job_stem, sex, _seen=None):
    """{family: stem} of the weapon sprites this body actually has in the client."""
    table = weapon_pins_table()
    prefix = f'{job_stem}_{SEX_DIR[sex]}_'
    found = {}
    for stem, record in table.items():
        if stem.startswith(prefix) and record['sex'] == SEX_DIR[sex]:
            found.setdefault(record['family'], stem)
    if found:
        return found
    seen = _seen or {job_stem}
    for source in (WEAPON_BORROW.get(job_stem), WEAPON_CROSS_SEX.get(job_stem)):
        if source and source not in seen:
            borrow = weapon_sets(source, sex, seen | {source})
            if borrow:
                return borrow
    return {}


